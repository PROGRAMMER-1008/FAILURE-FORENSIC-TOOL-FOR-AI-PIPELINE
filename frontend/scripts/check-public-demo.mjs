import {chromium, expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.FF_PUBLIC_DEMO_URL || 'http://127.0.0.1:18768');
await expect(page.locator('#output')).toContainText('999 EUR');
await page.locator('[data-step=classify]').click();
await expect(page.locator('#output')).toContainText('invoice');
await page.locator('[data-step=summarize]').click();
await expect(page.locator('#output')).toContainText('999 EUR');
await page.locator('#amount').fill('814');await page.locator('#apply').click();
await expect(page.locator('#match')).toHaveText('Matches the source amount');
await expect(page.locator('.comparison > div').first()).toContainText('999 EUR');
await page.locator('#amount').fill('');await page.locator('#apply').click();
await expect(page.locator('#feedback')).toContainText('Enter a whole number');
await page.locator('#reset').click();await expect(page.locator('#new-amount')).toHaveText('999 EUR');
await page.locator('[data-step=extract]').click();
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'../launch/public-demo-desktop.png',fullPage:true});
expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'../launch/public-demo-mobile.png',fullPage:true});
expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
expect(errors).toEqual([]);
await browser.close();console.log('Public demo: interaction, input validation, desktop/mobile accessibility, no overflow and no JS errors passed.');
